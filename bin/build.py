#!/usr/bin/env python3
"""db-triage build and validation tool.

Two jobs, in this order:

  --check     validate that the registry, the check SQL files, the reference
              documents and SKILL.md agree with each other. Exits 1 on any real
              inconsistency and prints every problem it found, not just the
              first one.

  (default)   regenerate everything that is derived from the registry:
              the threshold defaults, the combined pass files, the
              Checks_by_Priority table, and the embedded fast pass in SKILL.md.

Python 3.9+, standard library only. No arguments are required; run it from
anywhere.

MySQL: this tool reads checks/registry-mysql.csv when that file exists and
merges it into the combined registry, and ignores it silently when it does not.
It generates PostgreSQL pass files by default; pass --engines postgres,mysql to
generate the MySQL ones too, which requires checks/mysql/ to be populated.
"""

import argparse
import csv
import os
import re
import sys
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

COLUMNS = [
    "check_id", "engine", "category", "priority", "title", "scope", "cost", "pass",
    "source", "min_version", "max_version", "run_on", "requires", "platform_skip",
    "platform_priority", "fix_effort", "fix_risk", "condition", "thresholds", "reads",
    "ref", "docs_url", "status", "since", "superseded_by", "threshold_changed",
]

PRIORITIES = {0, 1, 5, 10, 20, 50, 100, 150, 200, 230, 240, 250, 254, 255}
SCOPES = {"cluster", "database", "schema", "relation", "index", "role", "setting",
          "session", "slot", "replica", "query", "host", "interview"}
SOURCES = {"sql", "os", "log", "interview", "derived", "external"}
PASSES = {"fast", "deep", "inventory"}
STATUSES = {"active", "retired", "planned"}
RUN_ON = {"primary", "standby", "any"}
EFFORT = {"S", "M", "L"}
RISK = {"low", "med", "high"}
ENGINES = {"postgresql", "mysql", "mariadb", "mysql,mariadb", "any"}

# Which engine directory a registry row's SQL lives in.
ENGINE_DIR = {"postgresql": "postgres", "mysql": "mysql", "mariadb": "mysql",
              "mysql,mariadb": "mysql"}
# Which reference document must carry the row's anchor.
ENGINE_REF = {"postgresql": "reference/checks-postgres.md", "any": "reference/checks-postgres.md",
              "mysql": "reference/checks-mysql.md", "mariadb": "reference/checks-mysql.md",
              "mysql,mariadb": "reference/checks-mysql.md"}

# A check whose scope is one of these reads per-database catalogs, so it belongs
# in the per-database pass and must be run once per scanned database. Everything
# else reads shared or cluster-wide state and runs once per cluster.
DATABASE_SCOPES = {"relation", "index", "schema", "query"}

# The checks SKILL.md's embedded fast pass must cover. Everything at priority 10
# or below that can be expressed as SQL, plus the inventory rows a reader needs
# in order to interpret the rest.
EMBEDDED_REQUIRED_EXTRA = {"PG-INFO-001", "PG-INFO-012", "PG-MEM-001", "PG-IDX-001",
                           "PG-CORR-004", "PG-REPL-004", "PG-BAK-006", "PG-WRAP-007",
                           "PG-LOCK-005", "PG-VAC-005", "PG-SCHEMA-001"}

SKILL_BEGIN = "<!-- BEGIN EMBEDDED FAST PASS — generated by bin/build.py; do not hand-edit -->"
SKILL_END = "<!-- END EMBEDDED FAST PASS -->"


class Problems:
    def __init__(self):
        self.errors = []
        self.warnings = []
        self.notes = []

    def error(self, msg):
        self.errors.append(msg)

    def warn(self, msg):
        self.warnings.append(msg)

    def note(self, msg):
        self.notes.append(msg)

    def report(self):
        for n in self.notes:
            print("note:    %s" % n)
        for w in self.warnings:
            print("warning: %s" % w)
        for e in self.errors:
            print("ERROR:   %s" % e)
        print("%d error(s), %d warning(s)" % (len(self.errors), len(self.warnings)))
        return 1 if self.errors else 0


def path(*parts):
    return os.path.join(ROOT, *parts)


def read_registry(p, prob):
    if not os.path.exists(p):
        return []
    with open(p, newline="", encoding="utf-8") as fh:
        rdr = csv.DictReader(fh)
        if rdr.fieldnames != COLUMNS:
            prob.error("%s: column order is %r, expected %r"
                       % (os.path.relpath(p, ROOT), rdr.fieldnames, COLUMNS))
            return []
        return list(rdr)


def load_all(prob):
    """PostgreSQL rows plus MySQL rows when that registry exists."""
    rows = read_registry(path("checks", "registry.csv"), prob)
    mysql_path = path("checks", "registry-mysql.csv")
    if os.path.exists(mysql_path):
        extra = read_registry(mysql_path, prob)
        prob.note("merged %d row(s) from checks/registry-mysql.csv" % len(extra))
        rows = rows + extra
    else:
        prob.note("checks/registry-mysql.csv is not present; MySQL rows are not part of this build")
    return rows


def threshold_var(check_id, key):
    """psql variable name for one threshold of one check."""
    return check_id.lower().replace("-", "_") + "_" + key


def parse_thresholds(row):
    out = []
    for pair in row["thresholds"].split(";"):
        pair = pair.strip()
        if not pair:
            continue
        k, _, v = pair.partition("=")
        out.append((k.strip(), v.strip()))
    return out


# --------------------------------------------------------------------------- validate

def validate(rows, prob):
    seen = {}
    per_category = {}
    for r in rows:
        cid = r["check_id"]
        if cid in seen:
            prob.error("%s: duplicate check_id" % cid)
            continue
        seen[cid] = r

        if not re.match(r"^(PG|MY|XX)-[A-Z]{2,6}-\d{3}$", cid):
            prob.error("%s: check_id does not match <ENGINE>-<CAT>-<NNN>" % cid)
        if r["engine"] not in ENGINES:
            prob.error("%s: engine %r is not one of %s" % (cid, r["engine"], sorted(ENGINES)))
        if r["category"] != cid.split("-")[1]:
            prob.error("%s: category %r does not match the id" % (cid, r["category"]))
        try:
            prio = int(r["priority"])
        except ValueError:
            prob.error("%s: priority %r is not an integer" % (cid, r["priority"]))
            prio = None
        if prio is not None and prio not in PRIORITIES:
            prob.error("%s: priority %d is not one of the documented bands %s"
                       % (cid, prio, sorted(PRIORITIES)))
        if r["scope"] not in SCOPES:
            prob.error("%s: scope %r is not one of %s" % (cid, r["scope"], sorted(SCOPES)))
        if r["cost"] not in {"0", "1", "2"}:
            prob.error("%s: cost %r is not 0, 1 or 2" % (cid, r["cost"]))
        if r["pass"] not in PASSES:
            prob.error("%s: pass %r is not one of %s" % (cid, r["pass"], sorted(PASSES)))
        if r["source"] not in SOURCES:
            prob.error("%s: source %r is not one of %s" % (cid, r["source"], sorted(SOURCES)))
        if r["run_on"] not in RUN_ON:
            prob.error("%s: run_on %r is not one of %s" % (cid, r["run_on"], sorted(RUN_ON)))
        if r["fix_effort"] not in EFFORT:
            prob.error("%s: fix_effort %r is not S, M or L" % (cid, r["fix_effort"]))
        if r["fix_risk"] not in RISK:
            prob.error("%s: fix_risk %r is not low, med or high" % (cid, r["fix_risk"]))
        if r["status"] not in STATUSES:
            prob.error("%s: status %r is not one of %s" % (cid, r["status"], sorted(STATUSES)))
        if r["status"] == "retired" and not r["superseded_by"]:
            prob.error("%s: retired rows must name a superseded_by" % cid)
        if not r["title"].strip():
            prob.error("%s: title is empty" % cid)
        if not r["condition"].strip():
            prob.error("%s: condition is empty - the human table has nothing to show" % cid)
        if not r["docs_url"].startswith("https://"):
            prob.error("%s: docs_url %r is not an https URL" % (cid, r["docs_url"]))
        if r["cost"] == "2" and r["pass"] != "deep":
            prob.error("%s: cost 2 checks must be in the deep pass, not %r" % (cid, r["pass"]))
        expect_ref = "%s#%s" % (ENGINE_REF[r["engine"]], cid.lower())
        if r["ref"] != expect_ref:
            prob.error("%s: ref is %r, expected %r" % (cid, r["ref"], expect_ref))

        key = (cid.split("-")[0], r["category"])
        per_category.setdefault(key, []).append(int(cid.split("-")[2]))

    for key, nums in sorted(per_category.items()):
        expected = list(range(1, len(nums) + 1))
        if sorted(nums) != expected:
            missing = sorted(set(expected) - set(nums))
            dupes = sorted(n for n in set(nums) if nums.count(n) > 1)
            prob.error("%s-%s: numbering is not contiguous from 001 (missing %s, duplicated %s). "
                       "A retired check keeps its row; it is never renumbered."
                       % (key[0], key[1], missing or "none", dupes or "none"))
    return seen


def validate_sql(rows, prob):
    """Registry rows with source=sql must have a check file, and vice versa."""
    planned = []
    for engine_dir in sorted({ENGINE_DIR[r["engine"]] for r in rows if r["engine"] in ENGINE_DIR}):
        checks_dir = path("checks", engine_dir, "checks")
        engine_rows = [r for r in rows if ENGINE_DIR.get(r["engine"]) == engine_dir]
        if not os.path.isdir(checks_dir):
            prob.note("checks/%s/checks/ is not present; skipping its file checks "
                      "(%d registry row(s) refer to it)" % (engine_dir, len(engine_rows)))
            continue
        on_disk = {f[:-4] for f in os.listdir(checks_dir) if f.endswith(".sql")}
        for r in engine_rows:
            cid = r["check_id"]
            want_file = r["source"] == "sql" and r["status"] == "active"
            if r["status"] == "planned":
                planned.append(cid)
                continue
            if want_file and cid not in on_disk:
                prob.error("%s: source=sql and status=active but checks/%s/checks/%s.sql is missing. "
                           "Either write it or set status=planned." % (cid, engine_dir, cid))
            if not want_file and cid in on_disk:
                prob.error("%s: checks/%s/checks/%s.sql exists but the registry row has "
                           "source=%s status=%s" % (cid, engine_dir, cid, r["source"], r["status"]))
        known = {r["check_id"] for r in engine_rows}
        for f in sorted(on_disk - known):
            prob.error("checks/%s/checks/%s.sql has no row in the registry" % (engine_dir, f))

        # Thresholds declared in the registry must actually be used by the SQL.
        #
        # The naming convention is engine-specific. PostgreSQL check files take
        # thresholds as psql variables namespaced by check id
        # (:'pg_wrap_001_xid_age'), because psql variables are global to the
        # session and a bare key like `top_n` would collide between checks. That
        # rule is enforced strictly. Other engines set their own session
        # variables and own their own convention, so for those the check is that
        # the key appears in the file at all, reported as a warning rather than
        # an error: this build must not impose PostgreSQL's naming on a tree it
        # does not own.
        strict = engine_dir == "postgres"
        for r in engine_rows:
            cid = r["check_id"]
            if cid not in on_disk:
                continue
            body = open(os.path.join(checks_dir, cid + ".sql"), encoding="utf-8").read()
            for k, v in parse_thresholds(r):
                if not v:
                    prob.error("%s: threshold %r has no default value" % (cid, k))
            if strict:
                declared = {threshold_var(cid, k) for k, _ in parse_thresholds(r)}
                used = set(re.findall(r":'([a-z0-9_]+)'", body))
                for v in sorted(declared - used):
                    prob.error("%s: registry declares threshold %s but the SQL never uses :'%s'"
                               % (cid, v[len(cid.lower().replace("-", "_")) + 1:], v))
                # A variable the SQL uses that is neither one of its own
                # thresholds nor a local \set is a typo waiting to silently
                # disable a check.
                local = set(re.findall(r"\\set\s+([a-z0-9_]+)", body))
                for v in sorted(used - declared - local):
                    prob.error("%s: SQL uses :'%s' which the registry does not declare as a threshold"
                               % (cid, v))
            else:
                for k, _ in parse_thresholds(r):
                    if k not in body:
                        prob.warn("%s: registry declares threshold %r but the string does not "
                                  "appear in checks/%s/checks/%s.sql - check the engine's "
                                  "threshold convention" % (cid, k, engine_dir, cid))
            if not re.search(r"^-- check:\s*%s\s*$" % re.escape(cid), body, re.M):
                prob.error("%s: check file does not start with the `-- check: %s` header" % (cid, cid))
    if planned:
        prob.note("%d check(s) marked status=planned and not implemented as SQL: %s"
                  % (len(planned), ", ".join(sorted(planned))))
    return planned


def validate_anchors(rows, prob):
    for ref_doc in sorted({ENGINE_REF[r["engine"]] for r in rows}):
        p = path(ref_doc)
        if not os.path.exists(p):
            n = len([r for r in rows if ENGINE_REF[r["engine"]] == ref_doc])
            prob.note("%s is not present; skipping anchor checks for its %d row(s)" % (ref_doc, n))
            continue
        text = open(p, encoding="utf-8").read()
        anchors = set(re.findall(r'<a id="([a-z0-9\-]+)"></a>', text))
        for r in rows:
            if ENGINE_REF[r["engine"]] != ref_doc:
                continue
            want = r["check_id"].lower()
            if want not in anchors:
                prob.error("%s: %s has no <a id=\"%s\"></a> anchor" % (r["check_id"], ref_doc, want))
        known = {r["check_id"].lower() for r in rows}
        for a in sorted(anchors - known):
            prob.warn("%s: anchor #%s has no registry row" % (ref_doc, a))


def validate_session_version(prob):
    version = open(path("VERSION"), encoding="utf-8").read().strip()
    p = path("checks", "postgres", "01_session.sql")
    if not os.path.exists(p):
        prob.error("checks/postgres/01_session.sql is missing")
        return version
    body = open(p, encoding="utf-8").read()
    m = re.search(r"\\set db_triage_version '([^']+)'", body)
    if not m:
        prob.error("checks/postgres/01_session.sql does not set db_triage_version")
    elif m.group(1) != version:
        prob.error("checks/postgres/01_session.sql sets db_triage_version '%s' but VERSION says '%s'"
                   % (m.group(1), version))
    return version


def validate_readonly(prob):
    """Grep lint: no .sql file outside tests/fixtures may mutate anything.

    Scope is deliberate and exact. Every `.sql` file in the repository is
    executable — the pass files are run with `psql -f`, and a reader may run any
    check file directly — so every one of them is linted. Markdown is not
    linted: `reference/checks-postgres.md` has to be able to print the ALTER
    SYSTEM that fixes a finding, and README has to be able to show the GRANT
    that creates the role. Those are commands for a human, presented as such.

    tests/fixtures/ is the single exception, and it carries its own loud header.
    """
    forbidden = re.compile(
        r"^\s*(INSERT\s+INTO|UPDATE\s+\w|DELETE\s+FROM|DROP\s+|CREATE\s+(TABLE|INDEX|EXTENSION|DATABASE|ROLE|USER|SCHEMA|FUNCTION|VIEW|SEQUENCE|TRIGGER|PUBLICATION|SUBSCRIPTION|MATERIALIZED)|ALTER\s+(TABLE|SYSTEM|DATABASE|ROLE|USER|INDEX|SEQUENCE|EXTENSION|COLLATION|SUBSCRIPTION)|TRUNCATE\s|GRANT\s|REVOKE\s|VACUUM\b|ANALYZE\b|REINDEX\b|CLUSTER\s+\w|CHECKPOINT\b|REFRESH\s+MATERIALIZED|SET\s+GLOBAL|SET\s+PERSIST|LOCK\s+TABLE|COPY\s+\w+\s+FROM|CALL\s|DO\s*\$)",
        re.I)
    forbidden_call = re.compile(
        r"\b(pg_terminate_backend|pg_cancel_backend|pg_drop_replication_slot|pg_create_\w*_replication_slot"
        r"|pg_stat_reset\w*|pg_stat_statements_reset|pg_switch_wal|pg_switch_xlog|pg_advisory_lock"
        r"|pg_promote|pg_reload_conf|pg_rotate_logfile|setval|nextval|pg_write_file|pg_read_binary_file)\s*\(",
        re.I)
    skip_dirs = {os.path.join(ROOT, "tests", "fixtures")}
    scanned = bad = 0
    for dirpath, dirs, files in os.walk(ROOT):
        if any(dirpath == d or dirpath.startswith(d + os.sep) for d in skip_dirs):
            dirs[:] = []
            continue
        if os.path.basename(dirpath) in (".git", "__pycache__"):
            dirs[:] = []
            continue
        for f in files:
            if not f.endswith(".sql"):
                continue
            fp = os.path.join(dirpath, f)
            rp = os.path.relpath(fp, ROOT)
            scanned += 1
            for i, line in enumerate(open(fp, encoding="utf-8", errors="replace"), 1):
                stripped = line.strip()
                if stripped.startswith("--") or stripped.startswith("\\echo"):
                    continue
                if forbidden.match(line):
                    prob.error("%s:%d: statement is not read-only: %s" % (rp, i, stripped[:90]))
                    bad += 1
                if forbidden_call.search(line) and "regexp_replace" not in line:
                    prob.error("%s:%d: calls a state-changing function: %s" % (rp, i, stripped[:90]))
                    bad += 1
    if not bad:
        prob.note("read-only lint: %d .sql file(s) scanned, no mutating statement found "
                  "(tests/fixtures/ is excluded by design)" % scanned)


def validate_embedded(rows, prob):
    """The compact embedded pass must agree with the registry and cover the required set."""
    p = path("checks", "postgres", "embedded-fast.sql")
    if not os.path.exists(p):
        prob.error("checks/postgres/embedded-fast.sql is missing; SKILL.md cannot be generated")
        return
    body = open(p, encoding="utf-8").read()
    marked = {}
    for m in re.finditer(r"^-- CHECK (\S+) P(\d+) (.+)$", body, re.M):
        marked[m.group(1)] = (int(m.group(2)), m.group(3).strip())
    by_id = {r["check_id"]: r for r in rows}
    for cid, (prio, title) in sorted(marked.items()):
        r = by_id.get(cid)
        if r is None:
            prob.error("embedded-fast.sql: marker for %s has no registry row" % cid)
            continue
        if int(r["priority"]) != prio:
            prob.error("embedded-fast.sql: %s marked P%d, registry says P%s" % (cid, prio, r["priority"]))
        if r["title"] != title:
            prob.error("embedded-fast.sql: %s title %r does not match the registry title %r"
                       % (cid, title, r["title"]))
    required = {r["check_id"] for r in rows
                if r["engine"] == "postgresql" and r["source"] == "sql"
                and r["status"] == "active" and int(r["priority"]) <= 10}
    required |= EMBEDDED_REQUIRED_EXTRA
    for cid in sorted(required - set(marked)):
        prob.error("embedded-fast.sql: required check %s is not covered "
                   "(everything at priority 10 or below, plus the documented inventory set)" % cid)
    prob.note("embedded fast pass covers %d check(s)" % len(marked))


# --------------------------------------------------------------------------- generate

BANNER = ("-- GENERATED by bin/build.py from checks/registry.csv and\n"
          "-- checks/postgres/checks/*.sql. Do not hand-edit: run bin/build.py.\n")


def gen_thresholds(rows, engine_dir, prob):
    out = [BANNER,
           "-- Default value for every overridable threshold used by the checks.\n"
           "-- Variable name = lower(check_id) with '-' replaced by '_', then '_' + the\n"
           "-- threshold key. A value supplied with `psql -v name=value` wins over the\n"
           "-- default below, which is how .db-triage.yml overrides reach the SQL.\n"]
    n = 0
    for r in rows:
        if ENGINE_DIR.get(r["engine"], "postgres" if r["engine"] == "any" else None) != engine_dir:
            continue
        pairs = parse_thresholds(r)
        if not pairs:
            continue
        out.append("-- %s" % r["check_id"])
        for k, v in pairs:
            var = threshold_var(r["check_id"], k)
            out.append("\\if :{?%s}\n\\else\n\\set %s %s\n\\endif" % (var, var, v))
            n += 1
        out.append("")
    p = path("checks", engine_dir, "lib", "thresholds.sql")
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", newline="\n", encoding="utf-8").write("\n".join(out) + "\n")
    return n


def gate_expression(r):
    """psql boolean expression deciding whether this check is eligible here."""
    parts = []
    if r["min_version"]:
        parts.append("current_setting('server_version_num')::int >= %d" % vernum(r["min_version"]))
    if r["max_version"]:
        parts.append("current_setting('server_version_num')::int < %d" % (vernum(r["max_version"]) + 10000))
    if r["run_on"] == "primary":
        parts.append("NOT pg_is_in_recovery()")
    elif r["run_on"] == "standby":
        parts.append("pg_is_in_recovery()")
    return " AND ".join(parts) if parts else None


def vernum(v):
    """'9.6' -> 90600, '13' -> 130000."""
    v = v.strip()
    if "." in v:
        major, minor = v.split(".", 1)
        return int(major) * 10000 + int(minor.split(".")[0]) * 100
    return int(v) * 10000


def gen_pass(rows, which, scope_set, out_name, prob):
    """Concatenate one group of PostgreSQL checks into a runnable psql script."""
    selected = [r for r in rows
                if r["engine"] == "postgresql" and r["status"] == "active"
                and r["source"] == "sql" and r["pass"] == which
                and (r["scope"] in DATABASE_SCOPES) == (scope_set == "database")]
    selected.sort(key=lambda r: (int(r["priority"]), r["check_id"]))

    thresholds = open(path("checks", "postgres", "lib", "thresholds.sql"), encoding="utf-8").read()
    session = open(path("checks", "postgres", "01_session.sql"), encoding="utf-8").read()

    head = [
        BANNER.rstrip(),
        "--",
        "-- Pass: %s, scope: %s. %d check(s), run in priority order so that if the run"
        % (which, scope_set, len(selected)),
        "-- is cut short the worst findings are already in hand.",
        "--",
        "-- Run it directly:",
        "--     psql \"$DSN\" -X -q -f %s --csv > triage.csv 2>&1" % out_name,
        "--",
        "-- Every check is bracketed by `@@CHECK <id>` and `@@END <id>` markers and",
        "-- returns the same six columns: check_id, scope, object, details,",
        "-- evidence_json, confidence. Checks that do not apply to this server version",
        "-- or to this node's role print `@@SKIP <id> <reason>` instead of running.",
        "--",
        "-- ON_ERROR_STOP is deliberately off: a privilege error on one check must not",
        "-- abandon the rest of the run. Errors appear on stderr next to their marker.",
        "",
        "\\set ON_ERROR_STOP off",
        "\\set QUIET on",
        "\\pset pager off",
        "",
        "-- ---- session safety (from 01_session.sql) ----",
        session.strip(),
        "",
        "-- ---- threshold defaults (from lib/thresholds.sql) ----",
        thresholds.strip(),
        "",
        "\\echo '@@RUN-BEGIN %s %s'" % (which, scope_set),
        "SELECT '@@TARGET ' || current_database() || ' ' || current_setting('server_version')"
        " || ' ' || CASE WHEN pg_is_in_recovery() THEN 'standby' ELSE 'primary' END AS t \\gset qq_",
        "\\echo :qq_t",
        "",
    ]
    body = []
    for r in selected:
        cid = r["check_id"]
        sql = open(path("checks", "postgres", "checks", cid + ".sql"), encoding="utf-8").read().rstrip()
        gate = gate_expression(r)
        var = "gate_" + cid.lower().replace("-", "_")
        body.append("-- ======== %s  P%s  %s ========" % (cid, r["priority"], r["title"]))
        if gate:
            body.append("SELECT (%s) AS %s \\gset" % (gate, var))
            body.append("\\if :%s" % var)
        body.append("\\echo '@@CHECK %s'" % cid)
        body.append(sql)
        body.append("\\echo '@@END %s'" % cid)
        if gate:
            body.append("\\else")
            reasons = []
            if r["min_version"]:
                reasons.append("needs PostgreSQL %s or newer" % r["min_version"])
            if r["max_version"]:
                reasons.append("only applies to PostgreSQL %s and older" % r["max_version"])
            if r["run_on"] != "any":
                reasons.append("%s only" % r["run_on"])
            body.append("\\echo '@@SKIP %s %s'" % (cid, "; ".join(reasons)))
            body.append("\\endif")
        body.append("")
    tail = ["\\echo '@@RUN-END %s %s'" % (which, scope_set)]

    p = path("checks", "postgres", out_name)
    open(p, "w", newline="\n", encoding="utf-8").write("\n".join(head + body + tail) + "\n")
    return len(selected)


def gen_checks_by_priority(rows, prob):
    active = [r for r in rows if r["status"] != "retired"]
    active.sort(key=lambda r: (int(r["priority"]), r["category"], r["check_id"]))
    high = {}
    for r in rows:
        key = "-".join(r["check_id"].split("-")[:2])
        high[key] = max(high.get(key, ""), r["check_id"])

    lines = [
        "# db-triage — checks by priority",
        "",
        "GENERATED by `bin/build.py` from `checks/registry.csv`. Do not hand-edit.",
        "",
        "Generated %s from registry schema 1. %d check(s): %d active, %d planned, %d retired."
        % (date.today().isoformat(), len(rows),
           len([r for r in rows if r["status"] == "active"]),
           len([r for r in rows if r["status"] == "planned"]),
           len([r for r in rows if r["status"] == "retired"])),
        "",
        "**CURRENT HIGH IDs** — to add a check, take the next number in its category and "
        "never reuse a retired one:",
        "",
        "> " + ", ".join("`%s`" % high[k] for k in sorted(high)),
        "",
        "Priority bands: **0** meta · **1** you get fired · **5** one step from fired · "
        "**10** active harm · **20** known-dangerous · **50** daily-job ceiling · "
        "**100** tuning detail · **150** hygiene · **200** non-default config · "
        "**230** security review · **240** workload profile · **250** inventory · "
        "**254** run metadata · **255** credits. See `reference/priorities.md`.",
        "",
    ]
    band = None
    for r in active:
        if r["priority"] != band:
            band = r["priority"]
            lines += ["", "## Priority %s" % band, "",
                      "| P | Category | Check | Finding | Scope | Cost | Pass | Source | Effort/Risk | Engine |",
                      "|---|---|---|---|---|---|---|---|---|---|"]
        status = "" if r["status"] == "active" else " _(%s)_" % r["status"]
        lines.append("| %s | %s | [`%s`](../%s) | %s%s | %s | %s | %s | %s | %s/%s | %s |"
                     % (r["priority"], r["category"], r["check_id"], r["ref"],
                        r["title"].replace("|", "\\|"), status, r["scope"], r["cost"],
                        r["pass"], r["source"], r["fix_effort"], r["fix_risk"], r["engine"]))
    lines.append("")
    p = path("docs", "Checks_by_Priority.md")
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", newline="\n", encoding="utf-8").write("\n".join(lines) + "\n")
    return len(active)


def gen_skill_block(prob):
    """Inline embedded-fast.sql into SKILL.md between the generated markers."""
    skill_path = path("SKILL.md")
    if not os.path.exists(skill_path):
        prob.warn("SKILL.md does not exist yet; skipping the embedded-block update")
        return 0
    embedded = open(path("checks", "postgres", "embedded-fast.sql"), encoding="utf-8").read().rstrip()
    # Drop the file's own provenance banner when inlining: it explains why the
    # file exists in the repository, which the skill reader does not need.
    lines = embedded.split("\n")
    while lines and (lines[0].startswith("--") or not lines[0].strip()):
        lines.pop(0)
    embedded = "\n".join(lines)
    text = open(skill_path, encoding="utf-8").read()
    if SKILL_BEGIN not in text or SKILL_END not in text:
        prob.error("SKILL.md is missing the embedded-fast-pass markers")
        return 0
    pre = text.split(SKILL_BEGIN)[0]
    post = text.split(SKILL_END)[1]
    new = pre + SKILL_BEGIN + "\n\n```sql\n" + embedded + "\n```\n\n" + SKILL_END + post
    open(skill_path, "w", newline="\n", encoding="utf-8").write(new)
    n = len(new.splitlines())
    if n > 900:
        prob.error("SKILL.md is %d lines; the budget is 900. Trim prose or the embedded pass." % n)
    else:
        prob.note("SKILL.md is %d lines of a 900-line budget" % n)
    return n


def gen_merged_registry(rows, prob):
    p = path("checks", "registry-all.csv")
    order = {"postgresql": 0, "any": 1, "mysql": 2, "mariadb": 3, "mysql,mariadb": 4}
    rows = sorted(rows, key=lambda r: (order.get(r["engine"], 9), int(r["priority"]), r["check_id"]))
    with open(p, "w", newline="\n", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=COLUMNS, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: r[k] for k in COLUMNS})
    return len(rows)


# --------------------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="validate only; do not write anything. Exits 1 on any inconsistency.")
    ap.add_argument("--engines", default="postgres",
                    help="comma-separated engines to generate pass files for (default: postgres)")
    args = ap.parse_args()

    prob = Problems()
    rows = load_all(prob)
    if not rows:
        prob.error("no registry rows loaded")
        return prob.report()

    validate(rows, prob)
    validate_sql(rows, prob)
    validate_anchors(rows, prob)
    validate_session_version(prob)
    validate_readonly(prob)
    validate_embedded(rows, prob)

    if args.check:
        return prob.report()

    if prob.errors:
        print("refusing to generate while the registry is inconsistent:")
        return prob.report()

    engines = [e.strip() for e in args.engines.split(",") if e.strip()]
    for engine_dir in engines:
        if engine_dir != "postgres" and not os.path.isdir(path("checks", engine_dir, "checks")):
            prob.warn("checks/%s/checks/ does not exist; not generating its pass files" % engine_dir)
            continue
        n = gen_thresholds(rows, engine_dir, prob)
        prob.note("wrote checks/%s/lib/thresholds.sql (%d threshold variables)" % (engine_dir, n))

    if "postgres" in engines:
        for which, scope_set, name in [
                ("fast", "cluster", "fast-cluster.sql"),
                ("fast", "database", "fast-database.sql"),
                ("deep", "cluster", "deep-cluster.sql"),
                ("deep", "database", "deep-database.sql")]:
            n = gen_pass(rows, which, scope_set, name, prob)
            prob.note("wrote checks/postgres/%s (%d checks)" % (name, n))
        # inventory is one file: the runner runs it once per scanned database.
        inv = [r for r in rows if r["engine"] == "postgresql" and r["pass"] == "inventory"
               and r["status"] == "active" and r["source"] == "sql"]
        n_c = gen_pass(rows, "inventory", "cluster", "inventory.sql", prob)
        prob.note("wrote checks/postgres/inventory.sql (%d cluster-scope checks; %d further "
                  "inventory checks are database-scope and are appended below)"
                  % (n_c, len(inv) - n_c))
        _append_database_inventory(rows, prob)

    n = gen_checks_by_priority(rows, prob)
    prob.note("wrote docs/Checks_by_Priority.md (%d rows)" % n)
    n = gen_merged_registry(rows, prob)
    prob.note("wrote checks/registry-all.csv (%d rows)" % n)
    gen_skill_block(prob)
    return prob.report()


def _append_database_inventory(rows, prob):
    """Database-scope inventory checks go into the same inventory.sql, after the
    cluster-scope ones, because the design specifies a single inventory file."""
    selected = [r for r in rows
                if r["engine"] == "postgresql" and r["status"] == "active"
                and r["source"] == "sql" and r["pass"] == "inventory"
                and r["scope"] in DATABASE_SCOPES]
    selected.sort(key=lambda r: (int(r["priority"]), r["check_id"]))
    if not selected:
        return
    p = path("checks", "postgres", "inventory.sql")
    text = open(p, encoding="utf-8").read()
    text = text.replace("\\echo '@@RUN-END inventory cluster'", "")
    parts = [text.rstrip(), "",
             "-- ---- database-scope inventory: run these once per scanned database ----", ""]
    for r in selected:
        cid = r["check_id"]
        sql = open(path("checks", "postgres", "checks", cid + ".sql"), encoding="utf-8").read().rstrip()
        gate = gate_expression(r)
        var = "gate_" + cid.lower().replace("-", "_")
        parts.append("-- ======== %s  P%s  %s ========" % (cid, r["priority"], r["title"]))
        if gate:
            parts.append("SELECT (%s) AS %s \\gset" % (gate, var))
            parts.append("\\if :%s" % var)
        parts.append("\\echo '@@CHECK %s'" % cid)
        parts.append(sql)
        parts.append("\\echo '@@END %s'" % cid)
        if gate:
            parts.append("\\else")
            parts.append("\\echo '@@SKIP %s version-or-role'" % cid)
            parts.append("\\endif")
        parts.append("")
    parts.append("\\echo '@@RUN-END inventory'")
    open(p, "w", newline="\n", encoding="utf-8").write("\n".join(parts) + "\n")


if __name__ == "__main__":
    sys.exit(main())
